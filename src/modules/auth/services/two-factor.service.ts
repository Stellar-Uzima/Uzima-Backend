import { Injectable, Logger, NotFoundException, BadRequestException } from '@nestjs/common';
import { InjectRepository } from '@nestjs/typeorm';
import { Repository } from 'typeorm';
import * as bcrypt from 'bcryptjs';
import * as crypto from 'crypto';
import { authenticator } from 'otplib';
import * as qrcode from 'qrcode';
import { User } from '@/entities/user.entity';
import { TwoFactor } from '@/database/entities/two-factor.entity';

@Injectable()
export class TwoFactorService {
  // Logger for recording service-level events and troubleshooting.
  private readonly logger = new Logger(TwoFactorService.name);

  constructor(
    @InjectRepository(User)
    private readonly userRepository: Repository<User>,
    @InjectRepository(TwoFactor)
    private readonly twoFactorRepository: Repository<TwoFactor>
  ) {
    // Allow TOTP verification within one time step before or after the current step.
    authenticator.options = { window: 1 };
  }

  async setupTwoFactor(userId: string) {
    // Ensure the user exists before configuring two-factor authentication.
    const user = await this.userRepository.findOne({ where: { id: userId } });
    if (!user) {
      throw new NotFoundException('User not found');
    }

    // Generate a new TOTP secret and a set of recovery codes.
    const secret = authenticator.generateSecret();
    const backupCodes = await this.generateBackupCodes();

    // Hash recovery codes before storing them so plaintext codes are not persisted.
    const backupCodeHashes = await Promise.all(
      backupCodes.map(async (code) => ({
        codeHash: await bcrypt.hash(code, 12),
        used: false,
      }))
    );

    // Reuse an existing record when resetting setup; otherwise create a new record.
    const existing = await this.twoFactorRepository.findOne({
      where: { user: { id: userId } },
    });
    const record = existing
      ? Object.assign(existing, {
          secret,
          enabled: false,
          backupCodes: backupCodeHashes,
        })
      : this.twoFactorRepository.create({
          user,
          userId,
          secret,
          enabled: false,
          backupCodes: backupCodeHashes,
        });

    // Persist the secret and hashed recovery codes while keeping 2FA disabled
    // until the user confirms the authenticator code.
    await this.twoFactorRepository.save(record);

    // Build the authenticator provisioning URL and convert it into a QR code.
    const otpauthUrl = authenticator.keyuri(user.email || userId, 'Stellar Uzima', secret);
    const qrCodeDataUrl = await qrcode.toDataURL(otpauthUrl);

    // Return the recovery codes once so the user can save them securely.
    return {
      otpauthUrl,
      qrCodeDataUrl,
      backupCodes,
    };
  }

  async confirmTwoFactor(userId: string, code: string) {
    // Retrieve the user's saved 2FA configuration.
    const record = await this.findRecord(userId);

    // Validate the code generated by the user's authenticator application.
    if (!authenticator.check(code, record.secret)) {
      throw new BadRequestException('Invalid authentication code');
    }

    // Enable 2FA only after the user successfully verifies a valid code.
    record.enabled = true;
    await this.twoFactorRepository.save(record);

    return { message: 'Two-factor authentication enabled successfully' };
  }

  async disableTwoFactor(userId: string, code: string) {
    // Retrieve the user's saved 2FA configuration.
    const record = await this.findRecord(userId);

    // Prevent disabling 2FA when it is already disabled.
    if (!record.enabled) {
      throw new BadRequestException('Two-factor authentication is not enabled');
    }

    // Require a valid authenticator code before disabling 2FA.
    if (!authenticator.check(code, record.secret)) {
      throw new BadRequestException('Invalid authentication code');
    }

    // Disable 2FA while retaining the configuration for potential future use.
    record.enabled = false;
    await this.twoFactorRepository.save(record);

    return { message: 'Two-factor authentication disabled successfully' };
  }

  async verifyBackupCode(userId: string, backupCode: string) {
    // Retrieve the user's 2FA configuration before checking recovery codes.
    const record = await this.findRecord(userId);

    // Reject recovery attempts if no backup codes are available.
    if (!record.backupCodes?.length) {
      throw new BadRequestException('No backup codes available');
    }

    // Find a matching recovery code that has not already been used.
    const codeEntry = await this.findBackupCodeEntry(record, backupCode);

    // Mark the matched code as used to prevent subsequent reuse.
    codeEntry.used = true;
    await this.twoFactorRepository.save(record);

    return {
      message: 'Backup code accepted. Two-factor authentication recovery successful',
    };
  }

  async getStatus(userId: string) {
    // Look up the user's 2FA configuration without throwing if none exists.
    const record = await this.twoFactorRepository.findOne({
      where: { user: { id: userId } },
    });

    // Report whether 2FA is enabled and whether a configuration exists.
    return {
      enabled: !!record?.enabled,
      hasSetup: !!record,
    };
  }

  private async findRecord(userId: string) {
    // Retrieve the user's 2FA record using the associated user ID.
    const record = await this.twoFactorRepository.findOne({
      where: { user: { id: userId } },
    });

    // Fail explicitly when the user has not configured 2FA.
    if (!record) {
      throw new NotFoundException('Two-factor authentication is not configured for this user');
    }

    return record;
  }

  private async findBackupCodeEntry(record: TwoFactor, code: string) {
    // Check each unused recovery code against the submitted plaintext code.
    for (const entry of record.backupCodes || []) {
      if (!entry.used && (await bcrypt.compare(code, entry.codeHash))) {
        // Return the matching entry so the caller can mark it as used.
        return entry;
      }
    }

    // Reject invalid codes and codes that have already been redeemed.
    throw new BadRequestException('Invalid or already used backup code');
  }

  private async generateBackupCodes(): Promise<string[]> {
    const codes: string[] = [];

    // Generate ten cryptographically random recovery codes.
    for (let i = 0; i < 10; i += 1) {
      // Generate four random bytes and encode them as eight uppercase hex characters.
      const raw = crypto.randomBytes(4).toString('hex').toUpperCase();
      codes.push(raw.slice(0, 8));
    }

    // Return plaintext codes for one-time delivery to the user.
    return codes;
  }
}
